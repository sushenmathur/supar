// Boot, data loading, routing and layout.
import { VERSION, SOURCE_DASHBOARDS } from './config.js?v=1';
import { connect, FatalConnectError, MESSAGES, inKioskSatellite, errorCode } from './connection.js?v=1';
import {
  parseDashParam, isStrategyDashboard, extractEntities, mergeExtractions, fallbackEntities,
  groupByArea, groupByDomain, applyEntityDiff,
} from './entities.js?v=1';
import { createTile, Sheet, CameraRefresher } from './tiles.js?v=1';
import { callService as hawsCallService } from './vendor/haws.mjs?v=1';

// One line per document load, so reloads can be told apart from hash switches.
console.info(`kiosk-test loaded v${VERSION}`);

const $ = (sel) => document.querySelector(sel);
const ks = window.kioskSatellite;
const states = new Map();
const tiles = new Map();
let conn = null;
let via = '';

// ---- Full-page message and small notices ----

function showMessage(text, kind = 'info') {
  const box = $('#message');
  box.dataset.kind = kind;
  box.querySelector('p').textContent = text;
  box.hidden = false;
  $('#app').hidden = true;
}

function hideMessage() {
  $('#message').hidden = true;
  $('#app').hidden = false;
}

function banner(text, details) {
  const b = document.createElement('div');
  b.className = 'banner';
  b.textContent = text;
  if (details?.length) {
    const d = document.createElement('details');
    const s = document.createElement('summary');
    s.textContent = 'Show';
    d.append(s, details.join(', '));
    b.append(' ', d);
  }
  $('#banners').append(b);
}

let toastTimer = 0;
function toast(text) {
  const t = $('#toast');
  t.textContent = text;
  t.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { t.hidden = true; }, 4000);
}

function setStatus(text) {
  const s = $('#status');
  s.textContent = text;
  s.hidden = !text;
}

// ---- Service calls ----

async function callService(domain, service, data) {
  try {
    await hawsCallService(conn, domain, service, data);
  } catch (err) {
    console.warn(`kiosk-test: ${domain}.${service} failed (${errorCode(err)})`);
    toast(`Couldn't run ${domain}.${service}${err?.message ? `: ${err.message}` : ''}`);
  }
}

// ---- Loading ----

const send = (msg) => conn.sendMessagePromise(msg);
const settle = (p) => p.then((value) => ({ ok: true, value }), (error) => ({ ok: false, error }));

async function load() {
  const dashboards = parseDashParam(location.search) ?? SOURCE_DASHBOARDS;
  const [statesRes, areas, devices, entityReg, services, ...configs] = await Promise.all([
    settle(send({ type: 'get_states' })),
    settle(send({ type: 'config/area_registry/list' })),
    settle(send({ type: 'config/device_registry/list' })),
    settle(send({ type: 'config/entity_registry/list_for_display' })),
    settle(send({ type: 'get_services' })),
    ...dashboards.map((url_path) => settle(send({ type: 'lovelace/config', url_path }))),
  ]);
  if (!statesRes.ok) throw statesRes.error;

  const knownIds = new Set(statesRes.value.map((s) => s.entity_id));
  const serviceNames = services.ok
    ? Object.entries(services.value).flatMap(([d, svcs]) => Object.keys(svcs).map((s) => `${d}.${s}`))
    : [];

  const extractions = [];
  let useFallback = false;
  configs.forEach((res, i) => {
    const label = dashboards[i] ?? 'default';
    if (!res.ok) {
      console.warn(`kiosk-test: lovelace/config ${label} failed (${errorCode(res.error)})`);
      banner(`Couldn't read dashboard "${label}" (${errorCode(res.error)}).`);
    } else if (isStrategyDashboard(res.value)) {
      useFallback = true;
    } else {
      extractions.push(extractEntities(res.value, knownIds, { services: serviceNames }));
    }
  });
  const { entities, missing } = mergeExtractions(extractions);

  let entityIds = entities;
  if (useFallback || entityIds.length === 0) {
    entityIds = fallbackEntities(knownIds, entityReg.ok ? entityReg.value : null);
    banner(`Showing all ${entityIds.length} visible entities: the dashboard ${useFallback ? 'is generated by a strategy' : 'gave no entities'}.`);
  }
  if (missing.length) {
    const one = missing.length === 1;
    banner(`${missing.length} entity ${one ? 'ID' : 'IDs'} on the dashboard ${one ? "doesn't" : "don't"} exist (renamed or deleted?).`, missing);
  }

  const registriesOk = areas.ok && devices.ok && entityReg.ok;
  if (!registriesOk) {
    const refused = [['area', areas], ['device', devices], ['entity', entityReg]].filter(([, r]) => !r.ok).map(([n]) => n);
    console.warn(`kiosk-test: registry refused: ${refused.join(', ')}`);
    banner('Grouped by type: this Home Assistant user may not read the area/device registries.');
  }
  // Seed tiles with the current states; the subscription keeps them up to date from here.
  const wanted = new Set(entityIds);
  for (const s of statesRes.value) if (wanted.has(s.entity_id)) states.set(s.entity_id, s);

  const groups = registriesOk
    ? groupByArea(entityIds, { areas: areas.value, devices: devices.value, entities: entityReg.value })
    : groupByDomain(entityIds);

  console.info(`kiosk-test: ${entityIds.length} entities in ${groups.length} groups via ${via}, ${missing.length} missing`);
  return { entityIds, groups };
}

// ---- Layout ----

function render(groups, ctx) {
  const chips = $('#chips');
  const sections = $('#sections');
  chips.replaceChildren(chip('all', 'All'));
  sections.replaceChildren();
  for (const g of groups) {
    chips.append(chip(g.id, g.name));
    const section = document.createElement('section');
    section.dataset.area = g.id;
    const h = document.createElement('h2');
    h.textContent = g.name;
    const grid = document.createElement('div');
    grid.className = 'grid';
    for (const id of g.entityIds) {
      const tile = createTile(id, ctx);
      tiles.set(id, tile);
      tile.update(states.get(id) ?? null);
      grid.append(tile.el);
    }
    section.append(h, grid);
    sections.append(section);
  }
}

function chip(id, label) {
  const a = document.createElement('a');
  a.className = 'chip';
  a.href = `#${encodeURIComponent(id)}`;
  a.dataset.area = id;
  a.textContent = label;
  return a;
}

// Navigation is hash-only, so Kiosk Satellite never reloads the page.
function route() {
  const target = decodeURIComponent(location.hash.slice(1)) || 'all';
  let found = target === 'all';
  for (const s of document.querySelectorAll('#sections section')) {
    const show = target === 'all' || s.dataset.area === target;
    s.hidden = !show;
    found ||= show;
  }
  for (const c of document.querySelectorAll('#chips .chip')) {
    const active = c.dataset.area === target;
    c.classList.toggle('active', active);
    if (active) c.setAttribute('aria-current', 'page'); else c.removeAttribute('aria-current');
    if (active) c.scrollIntoView({ block: 'nearest', inline: 'center' });
  }
  $('#not-found').hidden = found;
  window.scrollTo(0, 0);
}

// ---- Live updates ----

async function subscribe(entityIds, sheet) {
  let replace = true;
  conn.addEventListener('ready', () => { replace = true; setStatus(''); });
  conn.addEventListener('disconnected', () => setStatus('Reconnecting…'));
  conn.addEventListener('reconnect-error', () => {
    showMessage(via === 'kiosk-satellite' ? MESSAGES.ksAuth : MESSAGES.noSession, 'error');
  });
  await conn.subscribeMessage((msg) => {
    const changed = applyEntityDiff(states, msg, replace);
    replace = false;
    for (const id of changed) {
      tiles.get(id)?.update(states.get(id) ?? null);
      sheet.update(id);
    }
  }, { type: 'subscribe_entities', entity_ids: entityIds });
}

// ---- Kiosk Satellite integration ----

function watchVisibility(cameras) {
  document.addEventListener('visibilitychange', () => cameras.setPaused('hidden', document.hidden));
  cameras.setPaused('hidden', document.hidden);
  if (!inKioskSatellite()) return;
  const onKioskState = (s) => cameras.setPaused('screensaver', Boolean(s?.screensaver?.active));
  window.addEventListener('kiosksatellite:kiosk-state', (e) => onKioskState(e.detail));
  ks.getKioskState?.().then(onKioskState, () => {});
}

// ---- Boot ----

async function boot() {
  showMessage('Connecting to Home Assistant…');
  try {
    ({ conn, via } = await connect({ onRetry: () => showMessage(MESSAGES.unreachable, 'retry') }));
  } catch (err) {
    if (err instanceof FatalConnectError) {
      console.warn(`kiosk-test: ${err.kind}`);
      showMessage(err.message, 'error');
      return;
    }
    throw err;
  }

  const getState = (id) => states.get(id);
  const cameras = new CameraRefresher(getState);
  const sheet = new Sheet({
    getState,
    callService,
    onOpenChange: (open) => { if (inKioskSatellite()) ks.setInteractionActive?.(open); },
  });
  watchVisibility(cameras);

  const { entityIds, groups } = await load();
  render(groups, { callService, openSheet: (id) => sheet.open(id), cameras });
  window.addEventListener('hashchange', route);
  route();
  hideMessage();
  await subscribe(entityIds, sheet);
}

boot().catch((err) => {
  console.error(`kiosk-test: start-up failed (${errorCode(err)})`);
  showMessage(`Something went wrong loading this page (${errorCode(err)}). Reload to try again.`, 'error');
});
